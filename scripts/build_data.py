def kata(s):
    return "".join(chr(ord(c) + 0x60) if "\u3041" <= c <= "\u3096" else c for c in s)

def load():
    kd = json.load(open(KANJI_SRC, encoding="utf-8"))
    n5k = {k: v for k, v in kd.items() if v.get("jlpt_new") == 5}
    rows = list(csv.DictReader(open(VOCAB_SRC, encoding="utf-8")))
    zh = {}
    for line in open(ZH_SRC, encoding="utf-8"):
        line = line.strip()
        if not line: continue
        i, g, u = line.split("|")
        zh[int(i)] = (g, int(u))
    assert len(zh) == len(rows), (len(zh), len(rows))
    return n5k, rows, zh

def main():
    n5k, rows, zh = load()
    vocab = []
    for i, r in enumerate(rows):
        g, u = zh[i]
        expr = r["expression"].strip()
        primary = expr.split(";")[0].strip()
        kanji_in = [c for c in primary if re.match(r"[一-鿿]", c)]
        ff = FALSE_FRIENDS.get(primary, "")
        vocab.append({
            "id": f"v{i+1:04d}", "unit": u, "expression": expr, "reading": r["reading"].strip(),
            "zh": g, "en": r["meaning"].strip(), "kanji": kanji_in,
            "n5_kanji": [c for c in kanji_in if c in n5k],
            "false_friend": ff,
        })
    # kanji unit = pinned theme, else earliest unit of a word using it
    first_use = defaultdict(lambda: 99)
    for v in vocab:
        for c in v["n5_kanji"]:
            first_use[c] = min(first_use[c], v["unit"])
    kanji = []
    for c, d in sorted(n5k.items(), key=lambda kv: kv[1]["freq"] or 9999):
        u = first_use[c] if first_use[c] != 99 else KANJI_PIN.get(c, 10)
        if c in "一二三四五": u = min(u, 1)
        kanji.append({
            "id": f"k{len(kanji)+1:03d}", "kanji": c, "unit": u, "traditional": TRAD.get(c, c),
            "shinjitai_differs": c in TRAD, "zh": KANJI_ZH.get(c, ""), "on": [kata(x) for x in d["readings_on"]],
            "kun": d["readings_kun"], "strokes": d["strokes"], "freq": d["freq"],
            "en": d["meanings"][0] if d["meanings"] else "",
        })
    kunit = {k["kanji"]: k["unit"] for k in kanji}
    # gating: word unlocks when all its N5 kanji are learned; word unit must be >= kanji unit
    for v in vocab:
        v["requires_kanji"] = [f"k{[k['kanji'] for k in kanji].index(c)+1:03d}" for c in v["n5_kanji"]]
        late = max([kunit[c] for c in v["n5_kanji"]] or [0])
        v["unit"] = max(v["unit"], late)
    grammar = []
    for i, (p, ex, jp, tr) in enumerate(GRAMMAR):
        grammar.append({"id": f"g{i+1:02d}", "unit": i // 6 + 1, "pattern": p, "zh": ex,
                        "example_jp": jp, "example_zh": tr})
    units = [{"unit": u, "title": t,
              "kanji": sum(1 for k in kanji if k["unit"] == u),
              "vocab": sum(1 for v in vocab if v["unit"] == u),
              "grammar": sum(1 for g in grammar if g["unit"] == u)} for u, t in UNITS.items()]
    data = {"meta": {"level": "N5", "version": "0.1", "generated": "2026-11-25",
                     "sources": [
                        "Kanji: davidluzgouveia/kanji-data (MIT), readings from KANJIDIC; WaniKani fields not used",
                        "Vocabulary: jamsinclair/open-anki-jlpt-decks (MIT), based on tanos.co.uk JLPT lists (CC BY)",
                        "Traditional Chinese glosses, units, grammar points: written for this project"]},
            "units": units, "kanji": kanji, "vocab": vocab, "grammar": grammar}
    json.dump(data, open(OUT, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("kanji", len(kanji), "vocab", len(vocab), "grammar", len(grammar))
    for u in units: print(u)
    print("false friends:", sum(1 for v in vocab if v["false_friend"]))

main()
